function buildTopicItems(labels: Array<[string, string, TopicItem['status']]>) {
  return labels.map(([key, label, status]) => ({
    key,
    label,
    shortLabel: label.slice(0, 2),
    status,
  }))
}

function buildFilterState(variable: string, minValue: number, maxValue: number): FilterState {
  return {
    depth: '表层',
    startPeriod: '1900-01',
    endPeriod: '2024-12',
    period: '2024-12',
    variable,
    showCurrent: true,
    showWindField: true,
    showProfilePoints: true,
    intensity: 68,
    minValue,
    maxValue,
  }
}

function monthly(values: number[]) {
  return values.map((value, index) => ({
    time: `${index + 1}`.padStart(2, '0'),
    value,
  }))
}

type PageDataSeed = Omit<PageData, 'trendPointsByTopic'> & {
  trendPointsByTopic: Record<string, TrendPoint[]>
}

function buildVariableSeries(baseSeries: TrendPoint[], _variable: string, variableIndex: number) {
  if (variableIndex === 0) {
    return baseSeries.map((point) => ({ ...point }))
  }

  return baseSeries.map((point, index) => ({
    time: point.time,
    value: Number((point.value * (0.9 + variableIndex * 0.08) + index * (0.03 + variableIndex * 0.01)).toFixed(2)),
  }))
}

function buildTrendSeriesMap(page: PageDataSeed) {
  return Object.fromEntries(
    Object.entries(page.trendPointsByTopic).map(([topicKey, baseSeries]) => {
      const labels = page.topicDetails[topicKey]?.labels ?? [topicKey]

      return [
        topicKey,
        Object.fromEntries(
          labels.map((label, index) => [label, buildVariableSeries(baseSeries, label, index)]),
        ),
      ]
    }),
  )
}

